#!/usr/bin/env python3
"""Export deterministic API artifacts without starting services or calling providers.

Run from the app's Python environment: python scripts/export_api.py [--check].
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
# main imports dotenv; pin provider secrets off before import. No app lifespan runs.
for name in ('LLM_API_KEY', 'OPENROUTER_API_KEY', 'VIDU_API_KEY', 'HYPERTEK_API_KEY', 'DECART_API_KEY', 'GEMINI_API_KEY'):
    os.environ[name] = ''
os.environ['SHADOW_MODE'] = 'mock'

from main import app  # noqa: E402
from conversation_tools import tool_schemas  # noqa: E402


def render_reference(spec: dict) -> str:
    lines = ['# HTTP API reference', '',
             'Generated by `python scripts/export_api.py`. See [mobile integration](../MOBILE_API.md) for authentication, streaming, media and native UI behavior.', '',
             'The authoritative machine-readable contract is [openapi.json](openapi.json). Dynamic JSON objects retain extensible fields; generated clients should preserve unknown properties.', '']
    for path, operations in spec['paths'].items():
        for method, op in operations.items():
            if method not in {'get', 'post', 'put', 'patch', 'delete', 'head', 'options'}:
                continue
            lines.extend([f'## {method.upper()} {path}', '', op.get('summary', ''), '',
                          f"Operation ID: `{op['operationId']}`. Authentication: {'required when access gate is enabled' if op.get('security', spec.get('security')) else 'public'}.", ''])
            if op.get('description'):
                lines.extend([op['description'], ''])
            for param in op.get('parameters', []):
                lines.append(f"- `{param['name']}` ({param['in']}, {'required' if param.get('required') else 'optional'}): `{json.dumps(param.get('schema', {}), ensure_ascii=False, sort_keys=True)}`")
            if op.get('parameters'):
                lines.append('')
            body = op.get('requestBody', {})
            for mime, media in body.get('content', {}).items():
                lines.extend([f"Request: `{mime}` ({'required' if body.get('required') else 'optional'}).", '', '```json', json.dumps(media.get('schema', {}), indent=2, ensure_ascii=False, sort_keys=True), '```', ''])
            lines.extend(['Responses:', ''])
            for status, response in op.get('responses', {}).items():
                content = ', '.join(f'`{mime}`' for mime in response.get('content', {}))
                lines.append(f"- `{status}`: {response.get('description', '')}" + (f' ({content})' if content else ''))
            lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in artifacts differ')
    args = parser.parse_args()
    spec = app.openapi()
    artifacts = {
        'docs/api/openapi.json': json.dumps(spec, indent=2, ensure_ascii=False, sort_keys=True) + '\n',
        'docs/api/tools.json': json.dumps(tool_schemas(), indent=2, ensure_ascii=False, sort_keys=True) + '\n',
        'docs/api/REFERENCE.md': render_reference(spec),
    }
    stale = []
    for rel, content in artifacts.items():
        path = ROOT / rel
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f'Wrote {rel}')
    if stale:
        print('API artifacts need regeneration: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
